"""Script draft + render manifest for a chosen topic — HyperFrames + GSAP spec, per the
ai-reference-videos playbook rules baked into the manifest itself:
- one slide per idea, meaningful inferred image used once, still base brought alive by
  popups/underlines/circles/cut-outs in smooth motion, fades between slides, NO slow zoom,
  NO repeated image or motion, comma/list changes visible as spoken
- subtitles: single clean line, spoken words in gold
- proofs: cinematic text reveals, full-screen zoomed (mouthfeed), cited text highlighted
- close ('what you can do'): animated checklist, items build one by one, moving highlight
- outro: first-video welcome, subscribe push, brass-arrow brand mark + catchphrase
- generated media (image/video gen, LTX-2.3 when rented) = metaphor/atmosphere ONLY, never proof
Every factual claim slot carries an evidence link or is marked UNVERIFIED.
Gate: manifest is the ONLY pre-publish approval (Gate 1). Status stays queued_manifest_gate.

SCRIPT PURITY (Oliver, 2026-10-30 — his strongest script rule): the narration talks ONLY
about the topic/concept and voices Oliver's opinions about that concept. It NEVER talks about
the production process, receipts/provenance, the pipeline, or the video's own attributes, and
it never twists his build directions into on-screen reasoning or presents obedience to them
as support inside the video. No meta commentary unless the pipeline itself is the topic.
VISUAL COVERAGE (Oliver, 2026-10-30; teardown backend/teardown/CHOREOGRAPHY-SPEC.md): every
narration beat gets a visual that SHOWS what is being talked about — generated image
visualising the narration, company/product logo card when a company is the subject, screen
proof, or generated motion clip. Words + word animation alone is not enough."""
import json
from pathlib import Path

# Hard script rules (Oliver, 2026-10-30) — every generated script is checked against these.
SCRIPT_PURITY_RULES = [
    "Topic only: the script talks about the topic/concept and voices Oliver's opinions about that concept — nothing else.",
    "Never mention the production process, how the video was made, or the pipeline (no pipeline talk unless the pipeline IS the topic).",
    "Never mention receipts, provenance, evidence-gathering, or verification work on screen — provenance lives in the manifest/notes, never in the narration.",
    "Never comment on the video's own attributes (its length, its visuals, its structure, 'in this video we will...') beyond a plain content promise in the hook.",
    "Never present obedience to Oliver's build directions as reasoning inside the video, and never twist his directions into script content.",
    "No AI-slop meta filler: no 'let's dive in' process narration, no self-referential framing of the channel's methods as a selling point.",
]

# Visual coverage rule (Oliver, 2026-10-30) — full template: backend/teardown/choreography.json
VISUAL_COVERAGE_RULE = (
    "Every narration beat must carry a hero visual that shows what is being talked about: "
    "a generated image visualising the narration, a company/product logo card when a company "
    "or product is the subject, a screen proof, or a generated motion clip. Words and word "
    "animation alone never count as a visual; no text-only stretch over ~4s. Hero asset "
    "changes at least every 20-45s; caption/headline-level change every 3-6s."
)

SEGMENTS = [
    ("Hook", "Topic in one sentence + why this week, dated evidence on screen"),
    ("Evidence", "Dated changelog / release / harvest evidence, cinematic text reveals, links cited in notes"),
    ("Live test / artifact", "Oliver's real artifact (from Brain angle): what ran, what did NOT run — honestly"),
    ("What breaks / watch", "Limits, costs, quota, VRAM, deprecations — the honest catch"),
    ("What you can do", "ANIMATED checklist close: items build in one by one, moving highlight, takeaway lands"),
    ("Outro", "Welcome to the channel / first-video framing, subscribe push, brass-arrow mark, catchphrase"),
]

def build(out_dir, topic, subniche, week, evidence_url="", angle=None, origin="automate"):
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    script_lines = [f"# Script draft — {topic}", f"Subniche: {subniche} | Week: {week} | Origin: {origin}",
                    "Status: DRAFT generated by backend — hands-free under blanket approval; publish waits on Gate 1 (full render manifest approval).",
                    f"Evidence: {evidence_url or 'UNVERIFIED — no evidence link attached; do not state as proven'}",
                    f"Brain angle: {angle['angle'] if angle else 'none indexed — artifact fit must be recorded before VO'}",
                    f"Brain source: {angle['source_ref'] if angle else ''}", ""]
    manifest = {"topic": topic, "subniche": subniche, "week": week, "origin": origin,
                "status": "queued_manifest_gate",
                "engine": {"composition": "HyperFrames", "animation": "GSAP (CustomEase butter curves, spring where specified)",
                           "media": "image generation + generated video clips (LTX-2.3 via rented GPU when available) as metaphor/atmosphere ONLY; overlays/captions composited in HyperFrames",
                           "voiceover": "Helio VO at natural pace, re-synced to word timestamps; subtitles single clean line, spoken word in gold"},
                "rules": ["one slide per idea", "no slow zoom", "no image or motion repeated",
                          "comma/list changes appear as spoken", "proofs are cinematic text reveals, full-screen, highlighted as spoken (mouthfeed)",
                          "no provenance/meta labels on frames (provenance lives in this manifest)",
                          "animated checklist close", "branded outro with subscribe + catchphrase",
                          "SCRIPT PURITY: narration covers the topic only — no process/receipt/pipeline/video-attribute talk (see SCRIPT_PURITY_RULES)",
                          "VISUAL COVERAGE: every narration beat shows what it talks about — generated image / logo card / screen proof / motion clip, never words alone (see VISUAL_COVERAGE_RULE)"],
                "script_purity_rules": SCRIPT_PURITY_RULES,
                "visual_coverage_rule": VISUAL_COVERAGE_RULE,
                "choreography": "backend/teardown/choreography.json (beat template distilled from teardown of 5 AI-niche channels, 2026-10-30)",
                "segments": []}
    for i, (title, note) in enumerate(SEGMENTS):
        script_lines += [f"## Segment {i+1} — {title}", f"VO draft slot: [{note} — write from evidence only.]", ""]
        manifest["segments"].append({"segment": i + 1, "title": title, "vo_note": note,
                                     "visual": {"label": "NOT RUN", "kind": "hyperframes_scene",
                                                "source_file": "", "generated_media": "specced at build; metaphor only if generated",
                                                "note": "Replace with reviewed capture (live / fetched render / screen record / livestream frame) or generated plate, path recorded here."}})
    (out / "script.md").write_text("\n".join(script_lines))
    (out / "render_manifest.json").write_text(json.dumps(manifest, indent=1))
    return str(out / "script.md"), str(out / "render_manifest.json")
